#!/usr/bin/env python3
"""Write a C header holding any number of SPIR-V modules as word arrays.

usage: mk-spirv-arrays.py OUT HEADER NAME=FILE [NAME=FILE ...]

The first line of OUT is a comment; `HEADER` is the sentence that says how the
modules were compiled. The gate's own tool (mk-spirv-header.py) predates this
and keeps its three fixed names; this one is for the steps after it, where the
shader set changes per experiment.
"""
import struct
import sys


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    out, header = sys.argv[1], sys.argv[2]
    pairs = []
    for argument in sys.argv[3:]:
        name, equals, path = argument.partition('=')
        if not equals or not name.isidentifier():
            sys.exit(f'{argument}: expected NAME=FILE')
        data = open(path, 'rb').read()
        if len(data) % 4:
            sys.exit(f'{path}: {len(data)} bytes is not a whole number of words')
        words = struct.unpack('<%dI' % (len(data) // 4), data)
        if words[0] != 0x07230203:
            sys.exit(f'{path}: not SPIR-V (magic {words[0]:#x})')
        pairs.append((name, words))

    with open(out, 'w') as f:
        f.write('/* Generated by tools/vulkan/mk-spirv-arrays.py -- do not edit.\n')
        f.write(' *\n *   ' + header + '\n */\n\n')
        for name, words in pairs:
            f.write(f'static const uint32_t {name}[] = {{\n')
            for i in range(0, len(words), 8):
                line = ', '.join(f'0x{word:08x}' for word in words[i:i + 8])
                f.write('\t' + line + ',\n')
            f.write('};\n\n')


if __name__ == '__main__':
    main()
