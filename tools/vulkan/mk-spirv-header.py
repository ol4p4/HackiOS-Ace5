#!/usr/bin/env python3
"""Write a C header holding the triangle's SPIR-V as words.

usage: mk-spirv-header.py triangle.vert.spv triangle.frag.spv triangle_spirv.h

The gate embeds its shaders rather than reading files: the root image carries the
program and nothing else, and a missing file would look like a shader bug.
"""
import struct
import sys


def words(path):
    data = open(path, 'rb').read()
    if len(data) % 4:
        sys.exit(f'{path}: {len(data)} bytes is not a whole number of words')
    out = struct.unpack('<%dI' % (len(data) // 4), data)
    if out[0] != 0x07230203:
        sys.exit(f'{path}: not SPIR-V (magic {out[0]:#x})')
    return out


def main():
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    vert, frag, frag_green, out = sys.argv[1:]
    with open(out, 'w') as f:
        f.write('/* Generated by tools/vulkan/mk-spirv-header.py -- do not edit.\n')
        f.write(' *\n *   glslangValidator -V --target-env vulkan1.0 -o triangle.vert.spv triangle.vert\n')
        f.write(' *   glslangValidator -V --target-env vulkan1.0 -o triangle.frag.spv triangle.frag\n')
        f.write(' *   glslangValidator -V --target-env vulkan1.0 -o triangle-green.frag.spv triangle-green.frag\n')
        f.write(' *   tools/vulkan/mk-spirv-header.py triangle.vert.spv triangle.frag.spv triangle-green.frag.spv triangle_spirv.h\n */\n')
        for name, path in (('triangle_vert_spirv', vert), ('triangle_frag_spirv', frag),
                           ('triangle_green_frag_spirv', frag_green)):
            w = words(path)
            f.write(f'\nstatic const uint32_t {name}[] = {{\n')
            for i in range(0, len(w), 8):
                f.write('\t' + ', '.join('0x%08x' % x for x in w[i:i + 8]) + ',\n')
            f.write('};\n')


if __name__ == '__main__':
    main()
